-- RPC 1: Buscar perguntas por dificuldade (SEM revelar a resposta correta)
CREATE OR REPLACE FUNCTION public.buscar_perguntas(p_dificuldade TEXT)
RETURNS TABLE (
    id BIGINT,
    enunciado TEXT,
    alternativa_a TEXT,
    alternativa_b TEXT,
    alternativa_c TEXT,
    alternativa_d TEXT,
    dificuldade TEXT
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT
        p.id,
        p.enunciado,
        p.alternativa_a,
        p.alternativa_b,
        p.alternativa_c,
        p.alternativa_d,
        p.dificuldade
    FROM public.perguntas p
    WHERE p.dificuldade = LOWER(TRIM(p_dificuldade));
$$;

-- RPC 2: Validar resposta do jogador no servidor (retorna booleano)
CREATE OR REPLACE FUNCTION public.validar_resposta(
    p_pergunta_id BIGINT,
    p_resposta TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.perguntas
        WHERE id = p_pergunta_id
          AND correta = UPPER(TRIM(p_resposta))
    );
$$;

-- RPC 3: Salvar partida com identificador único (idempotente contra duplicidades)
CREATE OR REPLACE FUNCTION public.salvar_partida(
    p_id UUID,
    p_apelido TEXT,
    p_valor_ganho NUMERIC,
    p_tempo_segundos NUMERIC,
    p_acertos INTEGER,
    p_motivo_encerramento TEXT
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_jogo_id UUID;
BEGIN
    -- Busca o identificador do jogo Código Milionário
    SELECT id INTO v_jogo_id
    FROM public.jogos
    WHERE nome = 'Código Milionário'
    LIMIT 1;

    -- Se não existir por algum motivo, cria automaticamente
    IF v_jogo_id IS NULL THEN
        INSERT INTO public.jogos (nome)
        VALUES ('Código Milionário')
        RETURNING id INTO v_jogo_id;
    END IF;

    -- Insere a partida vinculada ao jogo. Em caso de reenvio do mesmo UUID,
    -- ignora silenciosamente sem duplicar o registro e sem gerar erro.
    INSERT INTO public.partidas (
        id,
        jogo_id,
        apelido,
        valor_ganho,
        tempo_segundos,
        acertos,
        motivo_encerramento,
        data_hora
    )
    VALUES (
        p_id,
        v_jogo_id,
        TRIM(p_apelido),
        p_valor_ganho,
        p_tempo_segundos,
        p_acertos,
        p_motivo_encerramento,
        NOW()
    )
    ON CONFLICT (id) DO NOTHING;

    RETURN p_id;
END;
$$;

-- RPC 4: Buscar ranking oficial (Top 10, melhor partida por jogador, desempate por tempo e data)
CREATE OR REPLACE FUNCTION public.buscar_ranking()
RETURNS TABLE (
    posicao INTEGER,
    apelido TEXT,
    valor_ganho NUMERIC,
    tempo_segundos NUMERIC,
    acertos INTEGER,
    data_hora TIMESTAMPTZ
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    WITH melhor_partida_por_jogador AS (
        SELECT
            p.apelido,
            p.valor_ganho,
            p.tempo_segundos,
            p.acertos,
            p.data_hora,
            ROW_NUMBER() OVER (
                PARTITION BY LOWER(TRIM(p.apelido))
                ORDER BY
                    p.valor_ganho DESC,
                    p.tempo_segundos ASC,
                    p.data_hora ASC
            ) AS rn
        FROM public.partidas p
        INNER JOIN public.jogos j ON j.id = p.jogo_id
        WHERE j.nome = 'Código Milionário'
    ),
    melhores_unicos AS (
        SELECT
            apelido,
            valor_ganho,
            tempo_segundos,
            acertos,
            data_hora
        FROM melhor_partida_por_jogador
        WHERE rn = 1
    )
    SELECT
        ROW_NUMBER() OVER (
            ORDER BY
                valor_ganho DESC,
                tempo_segundos ASC,
                data_hora ASC
        )::INTEGER AS posicao,
        apelido,
        valor_ganho,
        tempo_segundos,
        acertos,
        data_hora
    FROM melhores_unicos
    ORDER BY
        valor_ganho DESC,
        tempo_segundos ASC,
        data_hora ASC
    LIMIT 10;
$$;

