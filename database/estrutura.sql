ALTER TABLE public.perguntas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partidas ENABLE ROW LEVEL SECURITY;

-- Política para leitura de jogos
DROP POLICY IF EXISTS "Permitir leitura de jogos" ON public.jogos;
CREATE POLICY "Permitir leitura de jogos"
ON public.jogos
FOR SELECT
TO anon, authenticated
USING (true);

-- Para perguntas e partidas, a segurança por padrão bloqueia SELECT/INSERT direto do cliente
-- evitando que jogadores vejam a coluna 'correta' ou alterem dados de partidas.
-- Toda a comunicação ocorre de maneira segura pelas funções RPC SECURITY DEFINER acima.

-- Conceder permissões de uso do schema e execução das funções às roles anon e authenticated
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT SELECT ON public.jogos TO anon, authenticated, service_role;

GRANT EXECUTE ON FUNCTION public.buscar_perguntas(TEXT) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.validar_resposta(BIGINT, TEXT) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.salvar_partida(UUID, TEXT, NUMERIC, NUMERIC, INTEGER, TEXT) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.buscar_ranking() TO anon, authenticated, service_role;
