-- ------------------------------------------------------------------------
-- 1. TABELA DE JOGOS
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.jogos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome TEXT NOT NULL UNIQUE
);

-- ------------------------------------------------------------------------
-- 2. TABELA DE PERGUNTAS
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.perguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado TEXT NOT NULL,
    alternativa_a TEXT NOT NULL,
    alternativa_b TEXT NOT NULL,
    alternativa_c TEXT NOT NULL,
    alternativa_d TEXT NOT NULL,
    correta CHAR(1) NOT NULL
        CHECK (correta IN ('A', 'B', 'C', 'D')),
    dificuldade TEXT NOT NULL
        CHECK (dificuldade IN ('facil', 'media', 'dificil'))
);

-- ------------------------------------------------------------------------
-- 3. TABELA DE PARTIDAS
-- ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.partidas (
    id UUID PRIMARY KEY,
    jogo_id UUID NOT NULL REFERENCES public.jogos(id),
    apelido TEXT NOT NULL CHECK (length(trim(apelido)) > 0),
    valor_ganho NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (valor_ganho >= 0),
    tempo_segundos NUMERIC(10,2) NOT NULL
        CHECK (tempo_segundos >= 0),
    acertos INTEGER NOT NULL DEFAULT 0
        CHECK (acertos BETWEEN 0 AND 9),
    motivo_encerramento TEXT NOT NULL,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ------------------------------------------------------------------------
-- 4. ÍNDICES DE PERFORMANCE
-- ------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_perguntas_dificuldade
ON public.perguntas(dificuldade);

CREATE INDEX IF NOT EXISTS idx_partidas_jogo
ON public.partidas(jogo_id);

CREATE INDEX IF NOT EXISTS idx_partidas_apelido
ON public.partidas(jogo_id, apelido);

CREATE INDEX IF NOT EXISTS idx_partidas_ranking
ON public.partidas(jogo_id, valor_ganho DESC, tempo_segundos ASC);

